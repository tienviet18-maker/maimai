/**
 * Adds tropical / Vietnamese staple foods from IFCT 2017 (ICMR-National Institute of Nutrition, India)
 * as a supplement to FOOD_MASTER. The main catalog (foods.json, nutritionLock) is not touched.
 *  in:  tools/food_sources/ifct2017/compositions_selected.json  (rows copied from @ifct2017/compositions)
 *       tools/food_labels/ifct2017_map.js                       (hand-checked vi/ja names by scientific name)
 *  out: www/data/foods/foods_ifct.json and foods_ifct.js (appends to window.FOOD_MASTER)
 * Run: node tools/import_ifct2017.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { PREP_LABELS, slug } = require('./relabel_foods_v2.js');

const ROOT = path.join(__dirname, '..');
const SRC = require('./food_sources/ifct2017/compositions_selected.json');
const MAP = require('./food_labels/ifct2017_map.js');
const OUT_DIR = path.join(ROOT, 'www', 'data', 'foods');
const SOURCE = 'IFCT_2017';
const SOURCE_VERSION = 'Indian Food Composition Tables 2017 (ICMR-NIN), via ' + SRC.package + ' ' + SRC.version;

function num(v, factor, decimals) {
  if (v === '' || v == null || isNaN(Number(v))) return null;
  const f = Math.pow(10, decimals);
  return Math.round(Number(v) * factor * f) / f;
}

function plain(s) {
  return String(s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd');
}

function build() {
  const byCode = {};
  SRC.rows.forEach((r) => { byCode[r.code] = r; });
  return Object.keys(MAP).sort().map((code) => {
    const r = byCode[code];
    if (!r) throw new Error('IFCT code missing from source extract: ' + code);
    const [vi, ja, category, family, prep, extra, enOverride] = MAP[code];
    const en = enOverride || (r.name + (r.scie ? ' (' + r.scie + ')' : ''));
    const base = slug(vi.split(',')[0]);
    const aliases = [];
    [en, r.name, r.scie, code, vi, plain(vi)].concat(extra || [], (extra || []).map(plain)).forEach((a) => {
      if (a && aliases.indexOf(a) < 0) aliases.push(a);
    });
    const provenance = { source: SOURCE, sourceId: code, sourceVersion: SOURCE_VERSION };
    return {
      id: 'ifct_' + code.toLowerCase(),
      type: 'master',
      nameVi: vi,
      nameJa: ja,
      nameEn: en,
      aliases,
      category,
      cuisine: 'vietnamese',
      source: SOURCE,
      sourceId: code,
      sourceVersion: SOURCE_VERSION,
      nutritionPer100g: {
        energyKcal: num(r.enerc, 1 / 4.184, 0),
        protein: num(r.protcnt, 1, 2),
        fat: num(r.fatce, 1, 2),
        carbohydrate: num(r.choavldf, 1, 2),
        fiber: num(r.fibtg, 1, 2),
        sodium: num(r.na, 1000, 1)
      },
      foodKey: 'ifct.' + base,
      family,
      preparation: prep,
      preparationLabel: Object.assign({}, PREP_LABELS[prep] || PREP_LABELS.unspecified),
      variantKey: 'ifct.' + base + '.' + prep,
      nutritionBasis: 'per_100g',
      provenance,
      searchPrimary: true,
      duplicateOf: null,
      duplicateGroupId: null,
      originalLabels: { nameEn: r.name, scientificName: r.scie || null },
      nameViStatus: 'curated',
      labelVersion: 2,
      nameEnStatus: enOverride ? 'curated' : 'source'
    };
  });
}

function main() {
  const foods = build();
  const json = JSON.stringify(foods);
  fs.writeFileSync(path.join(OUT_DIR, 'foods_ifct.json'), json);
  fs.writeFileSync(path.join(OUT_DIR, 'foods_ifct.js'),
    '/* AUTO-GENERATED by tools/import_ifct2017.js — do not edit. Source: ' + SOURCE_VERSION + '. */\n' +
    'window.FOOD_MASTER = (Array.isArray(window.FOOD_MASTER) ? window.FOOD_MASTER : []).concat(' + json + ');\n');
  console.log('IFCT 2017 supplement: ' + foods.length + ' foods');
}

if (require.main === module) main();
module.exports = { build };
