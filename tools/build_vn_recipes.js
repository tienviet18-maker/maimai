/**
 * Builds standard Vietnamese dishes from tools/food_recipes/vn_recipes.js.
 * Every number is calculated with www/js/food/recipe_builder.js from the ingredients' sourced per-100 g values
 * (MEXT, USDA, IFCT 2017). Rows are marked provenanceType "calculated" and carry their ingredient list.
 *  out: www/data/foods/foods_vn_recipes.json and foods_vn_recipes.js (appends to window.FOOD_MASTER)
 * Run: node tools/build_vn_recipes.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { PREP_LABELS } = require('./relabel_foods_v2.js');
const { computeRecipe, recipeRecord } = require('../www/js/food/recipe_builder.js');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'www', 'data', 'foods');
const RECIPES = require('./food_recipes/vn_recipes.js');
const SOURCE = 'MAIMAI_RECIPE';
const SOURCE_VERSION = 'MaiMai standard recipes v1 (calculated from MEXT 2023 / USDA FDC / IFCT 2017 ingredients)';

function plain(s) {
  return String(s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd');
}

function catalog() {
  const all = JSON.parse(fs.readFileSync(path.join(DIR, 'foods.json'), 'utf8'))
    .concat(JSON.parse(fs.readFileSync(path.join(DIR, 'foods_ifct.json'), 'utf8')));
  const byId = {};
  all.forEach((f) => { byId[f.id] = f; });
  return byId;
}

function build() {
  const byId = catalog();
  return Object.keys(RECIPES).map((key) => {
    const r = RECIPES[key];
    const items = r.ingredients.map(([id, grams]) => {
      if (!byId[id]) throw new Error(key + ': unknown ingredient ' + id);
      return { food: byId[id], grams };
    });
    const calc = computeRecipe(items);
    if (!calc.ok || Object.keys(calc.per100g).some((k) => calc.per100g[k] == null)) {
      throw new Error(key + ': an ingredient lacks a nutrient, cannot calculate');
    }
    const aliases = [];
    [r.vi, plain(r.vi), r.en, r.ja].concat(r.aliases || [], (r.aliases || []).map(plain)).forEach((a) => {
      if (a && aliases.indexOf(a) < 0) aliases.push(a);
    });
    return {
      id: 'recipe_vn_' + key,
      type: 'master',
      nameVi: r.vi,
      nameJa: r.ja,
      nameEn: r.en,
      aliases,
      category: 'dish',
      cuisine: 'vietnamese',
      source: SOURCE,
      sourceId: key,
      sourceVersion: SOURCE_VERSION,
      provenanceType: 'calculated',
      nutritionPer100g: calc.per100g,
      foodKey: 'vn_dish.' + key,
      family: 'dish',
      preparation: 'cooked',
      preparationLabel: Object.assign({}, PREP_LABELS.cooked),
      variantKey: 'vn_dish.' + key + '.standard',
      nutritionBasis: 'per_100g',
      provenance: { source: SOURCE, sourceId: key, sourceVersion: SOURCE_VERSION, method: 'sum of ingredient rows' },
      recipe: recipeRecord(items),
      servings: [{ key: 'serving', grams: calc.finalGrams, label: r.serving }],
      defaultGrams: calc.finalGrams,
      searchPrimary: true,
      duplicateOf: null,
      duplicateGroupId: null,
      originalLabels: { nameEn: r.en },
      nameViStatus: 'curated',
      labelVersion: 2,
      nameEnStatus: 'curated'
    };
  });
}

function main() {
  const foods = build();
  const json = JSON.stringify(foods);
  fs.writeFileSync(path.join(DIR, 'foods_vn_recipes.json'), json);
  fs.writeFileSync(path.join(DIR, 'foods_vn_recipes.js'),
    '/* AUTO-GENERATED by tools/build_vn_recipes.js — do not edit. ' + SOURCE_VERSION + '. */\n' +
    'window.FOOD_MASTER = (Array.isArray(window.FOOD_MASTER) ? window.FOOD_MASTER : []).concat(' + json + ');\n');
  foods.forEach((f) => {
    const g = f.defaultGrams, n = f.nutritionPer100g;
    console.log(f.nameVi.padEnd(44) + String(g).padStart(4) + ' g  ' + Math.round(n.energyKcal * g / 100) + ' kcal  P' +
      Math.round(n.protein * g / 100) + ' F' + Math.round(n.fat * g / 100) + ' C' + Math.round(n.carbohydrate * g / 100) + '  Na ' + Math.round(n.sodium * g / 100));
  });
}

if (require.main === module) main();
module.exports = { build };
